#!/usr/bin/env python3
"""Resolves the designation-based sources in this directory against the Yale Bright Star
Catalogue and writes the HR-number assets the app bundles.

    python tools/constellations/gen_assets.py

Reads   tools/constellations/constellations.src, star_names.src, app/src/main/assets/bsc5.dat
Writes  app/src/main/assets/constellations.txt, app/src/main/assets/star_names.txt
Exits non-zero (and writes nothing) if any designation cannot be resolved.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parents[1] / "app" / "src" / "main" / "assets"
GREEK = set("Alp Bet Gam Del Eps Zet Eta The Iot Kap Lam Mu Nu Xi Omi Pi Rho Sig Tau Ups Phi Chi Psi Ome".split())

BAYER = re.compile(r"^([A-Z][a-z]{1,2})(\d?)(?:\s+([A-Za-z]{2,3}))?$")
FLAMSTEED = re.compile(r"^(\d+)(?:\s+([A-Za-z]{2,3}))?$")


def load_bsc():
    rows = []
    for line in (ASSETS / "bsc5.dat").read_text(encoding="ascii").splitlines():
        line = line.ljust(197)
        try:
            hr = int(line[0:4])
            vmag = float(line[102:107])
            int(line[75:77])  # has a J2000 position
        except ValueError:
            continue
        rows.append({
            "hr": hr,
            "vmag": vmag,
            "flamsteed": int(line[4:7]) if line[4:7].strip().isdigit() else None,
            "bayer": line[7:10].strip(),
            "sup": line[10:11].strip(),
            "const": line[11:14].strip(),
        })
    return rows


ROWS = load_bsc()
BY_HR = {r["hr"]: r for r in ROWS}


def resolve(token, default_const):
    """Returns an HR number for a designation token."""
    token = token.strip()
    if token.startswith("#"):
        hr = int(token[1:])
        if hr not in BY_HR:
            raise ValueError(f"unknown HR {hr}")
        return hr
    m = BAYER.match(token)
    if m and m.group(1) in GREEK:
        letter, sup, const = m.group(1), m.group(2), m.group(3) or default_const
        pool = [r for r in ROWS if r["bayer"] == letter and r["const"] == const]
        exact = [r for r in pool if r["sup"] == sup]
        if not exact and not sup:
            exact = [r for r in pool if r["sup"] == "1"]
        if not exact:
            raise ValueError(f"no star {token!r} in {const}")
        return min(exact, key=lambda r: r["vmag"])["hr"]
    m = FLAMSTEED.match(token)
    if m:
        number, const = int(m.group(1)), m.group(2) or default_const
        pool = [r for r in ROWS if r["flamsteed"] == number and r["const"] == const]
        if not pool:
            raise ValueError(f"no star {token!r} in {const}")
        return min(pool, key=lambda r: r["vmag"])["hr"]
    raise ValueError(f"cannot parse designation {token!r}")


def data_lines(path):
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            yield line


def build_constellations():
    out, errors = [], []
    for line in data_lines(HERE / "constellations.src"):
        abbr, name, genitive, figure = (p.strip() for p in line.split("|"))
        polylines = []
        for polyline in figure.split("/"):
            try:
                hrs = [resolve(t, abbr) for t in polyline.split("-")]
            except ValueError as e:
                errors.append(f"{abbr} ({name}): {e}")
                continue
            polylines.append("-".join(str(h) for h in hrs))
        out.append(f"{abbr}|{name}|{genitive}|{'/'.join(polylines)}")
    return out, errors


def build_names():
    out, errors, seen = [], [], {}
    for line in data_lines(HERE / "star_names.src"):
        name, designation = (p.strip() for p in line.split("|"))
        try:
            hr = resolve(designation, None)
        except ValueError as e:
            errors.append(f"{name}: {e}")
            continue
        if hr in seen:
            errors.append(f"{name}: HR {hr} already named {seen[hr]}")
            continue
        seen[hr] = name
        out.append(f"{hr}|{name}|{designation}")
    return out, errors


def main():
    constellations, errors = build_constellations()
    names, name_errors = build_names()
    errors += name_errors
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    (ASSETS / "constellations.txt").write_text(
        "# Constellation stick figures: Abbr|Name|Genitive|HR-HR-HR/HR-HR...\n"
        "# Generated by tools/constellations/gen_assets.py from constellations.src; do not edit by hand.\n"
        "# Hand-authored for Skyglass (no third-party figure data). Stars are identified by Yale Bright\n"
        "# Star Catalogue (5th ed.) HR numbers.\n"
        + "\n".join(constellations) + "\n",
        encoding="utf-8", newline="\n")
    (ASSETS / "star_names.txt").write_text(
        "# Proper star names: HR|Name|Designation\n"
        "# Generated by tools/constellations/gen_assets.py from star_names.src; do not edit by hand.\n"
        "# Names follow the IAU Working Group on Star Names (WGSN) list.\n"
        + "\n".join(names) + "\n",
        encoding="utf-8", newline="\n")
    print(f"constellations.txt: {len(constellations)} figures; star_names.txt: {len(names)} names")


if __name__ == "__main__":
    main()
